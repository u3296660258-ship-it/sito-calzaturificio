let currentLang = 'it';

function applyTranslations(){
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(translations[key]) el.textContent = translations[key][currentLang];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const key = el.getAttribute('data-i18n-ph');
    if(translations[key]) el.setAttribute('placeholder', translations[key][currentLang]);
  });
  const html = document.getElementById('htmlRoot');
  if(html) html.lang = currentLang;
  const langBtn = document.getElementById('langBtn');
  if(langBtn) langBtn.textContent = currentLang === 'it' ? 'EN' : 'IT';
  if(typeof renderCollection === 'function') renderCollection();
}

document.addEventListener('DOMContentLoaded', () => {
  const langBtn = document.getElementById('langBtn');
  if(langBtn){
    langBtn.addEventListener('click', ()=>{
      currentLang = currentLang === 'it' ? 'en' : 'it';
      applyTranslations();
    });
  }

  const toggle = document.getElementById('navtoggle');
  const links = document.getElementById('navlinks');
  if(toggle && links){
    toggle.addEventListener('click', () => {
      const open = links.classList.toggle('open');
      toggle.setAttribute('aria-expanded', open);
    });
  }

  const io = new IntersectionObserver((entries) => {
    entries.forEach(e => { if(e.isIntersecting) e.target.classList.add('visible'); });
  }, {threshold:0.15});
  document.querySelectorAll('.reveal').forEach(el => io.observe(el));

  const newsForm = document.getElementById('newsForm');
  if(newsForm){
    newsForm.addEventListener('submit', function(e){
      e.preventDefault();
      this.querySelector('button').textContent = currentLang === 'it' ? 'Iscritta ✓' : 'Subscribed ✓';
    });
  }

  applyTranslations();
});
